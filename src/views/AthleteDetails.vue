              <span class="text-h5">{{ getInitials(athlete.first_name, athlete.last_name) }}</span>
            </v-avatar>
            <div>
              <h2 class="text-h4 font-weight-bold">{{ athlete.first_name }} {{ athlete.last_name }}</h2>
              <p class="text-grey">{{ athlete.email }}</p>

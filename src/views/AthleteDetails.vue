<script setup>
import { ref, onMounted, computed } from 'vue'
import { useRouter, useRoute } from 'vue-router'
import { useStore } from 'vuex'
import Utils from '../config/utils'
import athleteServices from '../services/athleteServices'
import goalServices from '../services/goalServices'
import exerciseServices from '../services/exerciseServices'
import exercisePlanServices from '../services/exercisePlanServices'

const router = useRouter()
const route = useRoute()
const store = useStore()

const user = ref(null)
const currentUser = computed(() => store.state.currentUser || store.state.loginUser)

const athleteId = computed(() => route.params.id)

const athlete = ref({
  user_id: null,
  first_name: '',
  last_name: '',
  email: '',
  age: null,
  gender: '',
  team: '',
  sport_type: '',
  totalWorkouts: 0,
  bio: ''
})

const activeTab = ref('goals')
const goals = ref([])
const workoutResults = ref([])
const athleteAssignedPlans = ref([])
const availablePlans = ref([])
const showAssignPlanDialog = ref(false)
const showRemovePlanDialog = ref(false)
const showDeleteGoalDialog = ref(false)
const planToRemove = ref(null)
const goalToDelete = ref(null)
const selectedPlanId = ref(null)
const loading = ref(true)
const error = ref(null)
const successMessage = ref(null)

// Goal creation
const showAddGoalDialog = ref(false)
const coachPlans = ref([])
const selectedPlanForGoal = ref(null)
const exercisesFromPlan = ref([])
const selectedExerciseForGoal = ref(null)
const loadingExercises = ref(false)

const newGoal = ref({
  planId: null,
  exerciseId: null,
  exerciseName: '',
  targetValue: null,
  currentValue: 0,
  unit: 'reps',
  description: '',
  targetDate: '',
  timeframe: 'week'
})

const unitOptions = [
  { title: 'Reps', value: 'reps' },
  { title: 'Weight (lbs)', value: 'lbs' },
  { title: 'Weight (kg)', value: 'kg' },
  { title: 'Time (minutes)', value: 'minutes' },
  { title: 'Distance (miles)', value: 'miles' },
  { title: 'Distance (km)', value: 'km' }
]

const timeframeOptions = [
  { title: 'This Week', value: 'week' },
  { title: 'This Month', value: 'month' },
  { title: 'Custom Date', value: 'custom' }
]

const autoGeneratedTitle = computed(() => {
  if (!selectedExerciseForGoal.value || !newGoal.value.targetValue) {
    return ''
  }
  
  const exercise = exercisesFromPlan.value.find(ex => ex.id === selectedExerciseForGoal.value)
  const exerciseName = exercise?.name || 'Exercise'
  
  return `${exerciseName}: ${newGoal.value.targetValue} ${newGoal.value.unit}`
})

const computedTargetDate = computed(() => {
  if (newGoal.value.timeframe === 'custom') {
    return newGoal.value.targetDate
  }
  
  const today = new Date()
  
  if (newGoal.value.timeframe === 'week') {
    const daysUntilSunday = 7 - today.getDay()
    today.setDate(today.getDate() + daysUntilSunday)
  } else if (newGoal.value.timeframe === 'month') {
    today.setMonth(today.getMonth() + 1, 0)
  }
  
  return today.toISOString().split('T')[0]
})

const exercises = ref([])

const showSuccess = (message) => {
  successMessage.value = message
  setTimeout(() => {
    successMessage.value = null
  }, 3000)
}

const fetchAthleteData = async () => {
  try {
    loading.value = true
    error.value = null
    
    const response = await athleteServices.getAthleteById(athleteId.value)
    athlete.value = response.data
    
  } catch (err) {
    if (err.response?.status === 401) {
      error.value = 'Session expired. Please log in again.'
      setTimeout(() => router.push('/'), 2000)
    } else {
      error.value = 'Unable to load athlete data. Please try again.'
    }
  } finally {
    loading.value = false
  }
}

const fetchAthleteGoals = async () => {
  try {
    const response = await goalServices.getGoalsByAthlete(athleteId.value)
    goals.value = response.data
  } catch (err) {
    if (err.response?.status === 401) {
      router.push('/')
    }
  }
}

const fetchAthleteResults = async () => {
  try {
    const response = await exerciseServices.getAthleteResultsForCoach(athleteId.value)
    workoutResults.value = response.data
  } catch (err) {
    if (err.response?.status === 401) {
      router.push('/')
    }
  }
}

const loadExercises = async () => {
  try {
    const response = await exerciseServices.getAllExercises()
    exercises.value = response.data
  } catch (err) {
    // Silently fail
  }
}

const fetchAthleteAssignedPlans = async () => {
  try {
    const response = await exercisePlanServices.getPlansByAthlete(athleteId.value)
    athleteAssignedPlans.value = response.data
  } catch (err) {
    // Silently fail
  }
}

const loadAvailablePlans = async () => {
  try {
    const response = await exercisePlanServices.getAllExercisePlans()
    availablePlans.value = response.data
  } catch (err) {
    error.value = 'Unable to load training plans'
  }
}

const loadCoachPlans = async () => {
  try {
    const response = await exercisePlanServices.getAllExercisePlans()
    coachPlans.value = response.data
  } catch (err) {
    error.value = 'Unable to load training plans'
  }
}

const onPlanSelected = async () => {
  if (!selectedPlanForGoal.value) {
    exercisesFromPlan.value = []
    selectedExerciseForGoal.value = null
    return
  }
  
  try {
    loadingExercises.value = true
    const response = await goalServices.getExercisesFromPlan(selectedPlanForGoal.value)
    exercisesFromPlan.value = response.data
    
    if (exercisesFromPlan.value.length > 0) {
      selectedExerciseForGoal.value = exercisesFromPlan.value[0].id
    }
  } catch (err) {
    error.value = 'Unable to load exercises from plan'
  } finally {
    loadingExercises.value = false
  }
}

const openAssignPlanDialog = () => {
  loadAvailablePlans()
  showAssignPlanDialog.value = true
}

const closeAssignPlanDialog = () => {
  showAssignPlanDialog.value = false
  selectedPlanId.value = null
}

const assignPlan = async () => {
  if (!selectedPlanId.value) {
    error.value = 'Please select a plan'
    return
  }

  try {
    await exercisePlanServices.assignPlanToAthlete(selectedPlanId.value, athleteId.value)
    showSuccess('Training plan assigned successfully')
    await fetchAthleteAssignedPlans()
    closeAssignPlanDialog()
  } catch (err) {
    error.value = err.response?.data?.message || 'Unable to assign plan. Please try again.'
  }
}

const confirmUnassignPlan = (assignmentId, planId) => {
  planToRemove.value = { assignmentId, planId }
  showRemovePlanDialog.value = true
}

const unassignPlan = async () => {
  if (!planToRemove.value) return

  try {
    await exercisePlanServices.unassignPlanFromAthlete(planToRemove.value.planId, athleteId.value)
    showRemovePlanDialog.value = false
    planToRemove.value = null
    showSuccess('Training plan unassigned successfully')
    await fetchAthleteAssignedPlans()
  } catch (err) {
    error.value = 'Unable to unassign plan. Please try again.'
  }
}

const goBack = () => {
  router.push({ name: 'coachDashboard' })  
}

const openAddGoalDialog = async () => {
  await loadCoachPlans()
  showAddGoalDialog.value = true
}

const closeAddGoalDialog = () => {
  showAddGoalDialog.value = false
  
  selectedPlanForGoal.value = null
  selectedExerciseForGoal.value = null
  exercisesFromPlan.value = []
  newGoal.value = {
    planId: null,
    exerciseId: null,
    exerciseName: '',
    targetValue: null,
    currentValue: 0,
    unit: 'reps',
    description: '',
    targetDate: '',
    timeframe: 'week'
  }
}

const createGoal = async () => {
  if (!selectedPlanForGoal.value) {
    error.value = 'Please select a training plan'
    return
  }
  
  if (!selectedExerciseForGoal.value) {
    error.value = 'Please select an exercise'
    return
  }
  
  if (!newGoal.value.targetValue || newGoal.value.targetValue <= 0) {
    error.value = 'Please enter a valid target value'
    return
  }
  
  try {
    const goalData = {
      athleteId: athleteId.value,
      title: autoGeneratedTitle.value,
      description: newGoal.value.description || `Goal for ${athlete.value.first_name} ${athlete.value.last_name}`,
      planId: selectedPlanForGoal.value,
      exerciseId: selectedExerciseForGoal.value,
      targetValue: newGoal.value.targetValue,
      currentValue: newGoal.value.currentValue,
      unit: newGoal.value.unit,
      targetDate: computedTargetDate.value
    }
    
    await goalServices.createGoalForAthlete(athleteId.value, goalData)
    await fetchAthleteGoals()
    closeAddGoalDialog()
    showSuccess('Goal created successfully')
    
  } catch (err) {
    if (err.response?.status === 401) {
      error.value = 'Session expired. Please log in again.'
      setTimeout(() => router.push('/'), 2000)
    } else {
      error.value = err.response?.data?.message || 'Unable to create goal. Please try again.'
    }
  }
}

const confirmDeleteGoal = (goal) => {
  goalToDelete.value = goal
  showDeleteGoalDialog.value = true
}

const deleteGoal = async () => {
  if (!goalToDelete.value) return

  try {
    await goalServices.deleteGoal(goalToDelete.value.id)
    await fetchAthleteGoals()
    showDeleteGoalDialog.value = false
    goalToDelete.value = null
    showSuccess('Goal deleted successfully')
  } catch (err) {
    if (err.response?.status === 401) {
      error.value = 'Session expired. Please log in again.'
      setTimeout(() => router.push('/'), 2000)
    } else {
      error.value = 'Unable to delete goal. Please try again.'
    }
  }
}

const getProgressColor = (progress) => {
  if (progress >= 75) return 'success'
  if (progress >= 50) return 'warning'
  return 'error'
}

const calculateProgress = (currentValue, targetValue) => {
  if (!targetValue || targetValue === 0) return 0
  return Math.min(Math.round((currentValue / targetValue) * 100), 100)
}

const formatDate = (date) => {
  if (!date) return ''
  const d = new Date(date)
  return d.toLocaleDateString('en-US', { month: '2-digit', day: '2-digit', year: 'numeric' })
}

const getInitials = (firstName, lastName) => {
  if (!firstName || !lastName) return '??'
  return `${firstName[0]}${lastName[0]}`.toUpperCase()
}

onMounted(async () => {
  user.value = Utils.getStore("user") || currentUser.value
  
  if (!user.value) {
    router.push('/')
  } else if (user.value.role !== 'coach') {
    error.value = 'Access denied. Coach role required.'
    setTimeout(() => router.push('/'), 2000)
  } else {
    await fetchAthleteData()
    await fetchAthleteGoals()
    await fetchAthleteResults()
    await loadExercises()
    await fetchAthleteAssignedPlans()
  }
})
</script>

